export type FlipBlock =
  | { type: 'p'; text: string }
  | { type: 'lead'; text: string }
  | { type: 'question'; text: string }
  | { type: 'bullets'; items: string[] }
  | { type: 'compare'; left: string; right: string; rows: [string, string][] };

export interface FlipPage {
  kicker: string;
  title: string;
  blocks: FlipBlock[];
}

export interface FlipVolume {
  id: 'vol-1' | 'vol-2';
  /** Running head printed at the top of each page. */
  runningHead: string;
  cover: string;
  pages: [FlipPage, FlipPage];
  /** Teaser for the "rest of the book" page. */
  ahead: string[];
  pageCount: number;
}

